"""Regenerates src/KanTuNext.Desktop/Resources/Icons.axaml from Material Design Icons (@mdi/svg).

Only the icons listed here end up in the app. SVGs are cached in .cache/mdi (git-ignored).
usage: python3 tools/gen_icons.py
"""
import os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CACHE = os.path.join(ROOT, ".cache", "mdi")
OUT = os.path.join(ROOT, "src", "KanTuNext.Desktop", "Resources", "Icons.axaml")
VERSION = "7.4.47"

ICONS = [
    # sidebar
    "folder-outline", "plus", "image-size-select-large", "monitor-screenshot", "play-circle-outline",
    "content-duplicate", "trash-can-outline", "thumb-up", "emoticon-neutral", "thumb-down",
    "chevron-right", "chevron-down",
    # toolbar
    "chevron-left", "magnify", "export-variant", "information-outline", "cog-outline",
    # viewer toolbar
    "thumb-up-outline", "emoticon-neutral-outline",
    "thumb-down-outline", "magnify-plus-outline", "magnify-minus-outline", "fit-to-screen-outline",
    "rotate-left", "dots-grid", "menu-left", "text-recognition",
    # sidebar toggle: after the traffic lights (macOS-style), hamburger where the caption buttons are on the right
    "dock-left", "menu",
    # viewer context menu and info panel
    "rotate-right", "content-copy", "folder-search-outline", "open-in-app", "close",
    "camera-iris", "map-marker-outline", "check", "hand-back-right", "hand-back-right-outline",
]

def path_of(name):
    p = os.path.join(CACHE, name + ".svg")
    if not os.path.exists(p):
        os.makedirs(CACHE, exist_ok=True)
        with urllib.request.urlopen(f"https://cdn.jsdelivr.net/npm/@mdi/svg@{VERSION}/svg/{name}.svg") as r:
            open(p, "wb").write(r.read())
    return re.search(r' d="([^"]+)"', open(p).read()).group(1)

lines = [
    "<!-- Generated by tools/gen_icons.py from Material Design Icons (@mdi/svg " + VERSION + "); do not edit. -->",
    '<ResourceDictionary xmlns="https://github.com/avaloniaui"',
    '                    xmlns:x="http://schemas.microsoft.com/winfx/2006/xaml">',
]
for name in ICONS:
    lines.append(f'  <StreamGeometry x:Key="Icon.{name}">{path_of(name)}</StreamGeometry>')
lines.append("</ResourceDictionary>")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"{len(ICONS)} icons -> {os.path.relpath(OUT, ROOT)}")
